export const LANGS = ['en', 'zh-TW', 'zh']

export function normalizeLang(value) {
  const raw = String(value || '').toLowerCase()
  if (raw === 'zh-tw' || raw === 'zh-hk' || raw === 'zh-mo' || raw === 'zh-hant') return 'zh-TW'
  if (raw === 'zh' || raw === 'zh-cn' || raw === 'zh-hans' || raw === 'zh-sg') return 'zh'
  if (raw === 'en') return 'en'
  return null
}

function getStoredLang() {
  if (typeof window === 'undefined') return 'en'
  const stored = normalizeLang(localStorage.getItem('aiusage-lang'))
  if (stored) return stored
  const nav = normalizeLang(window.navigator?.language)
  return nav || 'en'
}

export const lang = writable(getStoredLang())

export function langLabel(code) {
  if (code === 'zh-TW') return '繁中'
  if (code === 'zh') return '简中'
  return 'EN'
}

export function toggleLang() {
  lang.update(current => {
    const idx = LANGS.indexOf(current)
    const next = LANGS[(idx + 1) % LANGS.length]
    if (typeof window !== 'undefined') localStorage.setItem('aiusage-lang', next)
    return next
  })
}

export const t = derived(lang, ($lang) => {
  const dict = translations[$lang] || translations.en
  return (key) => {
    const parts = key.split('.')
    let result = dict
    for (const part of parts) {
      result = result?.[part]
    }
    return result || key
  }
})
